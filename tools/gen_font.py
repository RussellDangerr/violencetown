def main():
    img = Image.new('RGBA', (SHEET_W, SHEET_H), (0, 0, 0, 0))
    for codepoint, rows in GLYPHS.items():
        idx = codepoint - 32
        col = idx % COLS
        row = idx // COLS
        for ry, row_str in enumerate(rows):
            for cx, ch in enumerate(row_str):
                if ch == '#':
                    img.putpixel((col * GLYPH_W + cx, row * GLYPH_H + ry), (255, 255, 255, 255))
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, '..', 'game', 'assets', 'font_8x8.png')
    out = os.path.abspath(out)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    img.save(out, optimize=True)
    print(f'Wrote {out} ({os.path.getsize(out)} bytes)')


if __name__ == '__main__':
    main()
