// item-sources.test.js — game/item-sources.js says where every item comes from, and it is
// current (plans/pc10-describe-item.md). tools/item-sources.mjs writes it from the maps,
// slots.js, the shops and the stock kits; this fails when the file lags the data.

import { test, describe } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { buildItemSources, render, zoneLabel } from '../tools/item-sources.mjs';
import onDisk from '../game/item-sources.js';
import { ITEMS } from '../game/items.js';
import { WEAPONS } from '../game/weapons.js';

const FILE = fileURLToPath(new URL('../game/item-sources.js', import.meta.url));

describe('item-sources.js', () => {
    test('is current: regenerate it with node tools/item-sources.mjs when this fails', async () => {
        const built = await buildItemSources();
        assert.equal(readFileSync(FILE, 'utf8').replace(/\r\n/g, '\n'), render(built));
    });

    test('is a module that exports its table, with a generated-by header', () => {
        const text = readFileSync(FILE, 'utf8');
        assert.match(text, /^\/\/ item-sources\.js: .*Generated by tools\/item-sources\.mjs/);
        assert.ok(text.includes('\nexport default {'));
    });

    test('names only items that exist', () => {
        for (const id of Object.keys(onDisk)) assert.ok(ITEMS[id] || WEAPONS[id], `${id} is not an item`);
    });

    test('every row has at least one source, and every name is plain text', () => {
        for (const [id, row] of Object.entries(onDisk)) {
            const lists = Object.values(row);
            assert.ok(lists.length > 0, id);
            for (const list of lists) {
                assert.ok(Array.isArray(list) && list.length > 0, `${id} has an empty list`);
                for (const name of list) assert.ok(typeof name === 'string' && name && !/[\[\]]/.test(name), `${id}: "${name}"`);
            }
            assert.deepEqual(Object.keys(row).filter(k => !['droppedBy', 'soldBy', 'foundIn'].includes(k)), [], id);
        }
    });

    test('pins the rows his examples rest on', () => {
        assert.ok(onDisk.tunnel_mushroom.droppedBy.includes('Red Fungus'));
        assert.deepEqual(onDisk.tunnel_mushroom.foundIn, ['Sewer']);
        assert.ok(onDisk.sludge_sack.droppedBy.includes('Violet Fungus'));
        assert.deepEqual(onDisk.alcohol, { soldBy: ['Hooch'] });
        assert.deepEqual(onDisk.catalytic_converter, { droppedBy: ['Were-Rat'] });
        assert.deepEqual(onDisk.act2_item_a, { droppedBy: ['Bigfoot', 'Ringmaster'] });
    });

    test('a zone name loses its brackets and its shouting; a placeholder falls back to the file name', () => {
        assert.equal(zoneLabel('sewer-map.json', 'SEWER'), 'Sewer');
        assert.equal(zoneLabel('frozen-map.json', '[Frozen Area]'), 'Frozen Area');
        assert.equal(zoneLabel('vault-map.json', '[TEXT]'), 'Vault');
        assert.equal(zoneLabel('bank-map.json', 'FIRST BLOOD BANK'), 'First Blood Bank');
    });
});
